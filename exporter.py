"""GitOps exporter: turn an optimiser result into config-repo files, optionally as a pull request.

Writes two things (both owned by the optimiser):
  envs/<service>-<site>/values.yaml     replicaCount, nodeSelector, memory request  -> ArgoCD (pods)
  infra/terraform/nodes.auto.tfvars.json  node_counts per site                        -> Terraform (nodes)
The image tag is owned by CI (apps/<service>/values.yaml), so writers never overwrite each other.
Folders without the GENERATED marker (hand-made environments) are never touched.
"""
import json
import re
import subprocess
import time
from pathlib import Path

from data import REGIONS, SITES

MARKER = "# GENERATED by placement-optimiser - do not edit by hand"
NODES_FILE = Path("infra/terraform/nodes.auto.tfvars.json")
NAME_RE = re.compile(r"^[a-z0-9]([-a-z0-9]*[a-z0-9])?$")


class ExportError(Exception):
    pass


def render_values(service, site, replicas, mem_mi, solver, scenario):
    return (f"{MARKER}\n"
            f"service: {service}\n"
            f"site: {site}\n"
            f"solver: {solver}\n"
            f"scenario: {scenario}\n"
            f"replicaCount: {replicas}\n"
            f"nodeSelector:\n"
            f"  region: {site}\n"
            f"podLabels:\n"
            f"  placement/site: {site}\n"
            f"resources:\n"
            f"  requests:\n"
            f"    memory: {mem_mi}Mi\n"
            f"  limits:\n"
            f"    memory: {mem_mi}Mi\n")


def _check_ok(result):
    if result.get("status") != "ok":
        raise ExportError(f"refusing to export a '{result.get('status')}' result: "
                          f"{result.get('reason', 'no valid placement')}")


def plan_envs(result):
    """{folder_name: values.yaml text}"""
    _check_ok(result)
    files = {}
    for service, p in result["placement"].items():
        for site, n in p["pods"].items():
            for part in (service, site):
                if not NAME_RE.match(part):
                    raise ExportError(f"'{part}' is not a valid Kubernetes/DNS name")
            files[f"{service}-{site}"] = render_values(service, site, n, p["mem_mi"],
                                                       result["solver"], result.get("scenario", ""))
    if not files:
        raise ExportError("placement has no pods; refusing to delete every environment")
    return files


def plan_nodes(result):
    """(counts dict, file text). Terraform rejects anything outside 1..4 per site / 9 in total."""
    _check_ok(result)
    counts = {j: int(result["nodes"][j]) for j in REGIONS}
    if any(not 1 <= n <= SITES[j]["max_nodes"] for j, n in counts.items()) or sum(counts.values()) > 9:
        raise ExportError(f"node plan {counts} is outside the lab limits (1-4 per site, 9 in total)")
    return counts, json.dumps({"node_counts": counts}, indent=2) + "\n"


def plan(result):
    """Everything that would be written, keyed by path relative to the config-repo."""
    files = {f"envs/{k}/values.yaml": v for k, v in plan_envs(result).items()}
    files[str(NODES_FILE)] = plan_nodes(result)[1]
    return files


def read_current(config_repo):
    """({(service, site): replicas}, {site: nodes}) as currently stored in the config-repo."""
    repo = Path(config_repo)
    pods, nodes = {}, {}
    envs = repo / "envs"
    if envs.is_dir():
        for d in envs.iterdir():
            f = d / "values.yaml"
            if f.is_file() and f.read_text().startswith(MARKER):
                t = f.read_text()
                svc = re.search(r"^service: (\S+)", t, re.M)
                site = re.search(r"^site: (\S+)", t, re.M)
                rep = re.search(r"^replicaCount: (\d+)", t, re.M)
                if svc and site and rep:
                    pods[(svc.group(1), site.group(1))] = int(rep.group(1))
    nf = repo / NODES_FILE
    if nf.is_file():
        nodes = json.loads(nf.read_text()).get("node_counts", {})
    return pods, nodes


def write_envs(result, config_repo, subdir="envs"):
    files = plan_envs(result)
    root = Path(config_repo) / subdir
    root.mkdir(parents=True, exist_ok=True)
    report = {"written": [], "unchanged": [], "removed": []}
    for name, text in files.items():
        f = root / name / "values.yaml"
        if f.exists() and f.read_text() == text:
            report["unchanged"].append(name)
            continue
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text)
        report["written"].append(name)
    for d in sorted(p for p in root.iterdir() if p.is_dir() and p.name not in files):
        f = d / "values.yaml"
        if f.exists() and f.read_text().startswith(MARKER):
            f.unlink()
            if not any(d.iterdir()):          # leave hand-added files alone
                d.rmdir()
            report["removed"].append(d.name)
    return report


def write_nodes(result, config_repo):
    counts, text = plan_nodes(result)
    f = Path(config_repo) / NODES_FILE
    old = json.loads(f.read_text()).get("node_counts") if f.exists() else None
    f.parent.mkdir(parents=True, exist_ok=True)
    if not f.exists() or f.read_text() != text:
        f.write_text(text)
    return {"old": old, "new": counts, "changed": old != counts}


def write_all(result, config_repo):
    # validate BOTH parts before touching the disk
    plan_envs(result), plan_nodes(result)
    return {"envs": write_envs(result, config_repo), "nodes": write_nodes(result, config_repo)}


# ----------------------------------------------------------------------------- summary / PR

def hourly_cost(nodes):
    return sum(SITES[j]["node_price"] * n for j, n in (nodes or {}).items())


def summary_markdown(result, before_pods, before_nodes):
    # No node file yet: the lab always starts with the minimum (one node per site)
    before_nodes = before_nodes or {j: SITES[j]["min_nodes"] for j in REGIONS}
    new_nodes = result["nodes"]
    old_cost, new_cost = hourly_cost(before_nodes), hourly_cost(new_nodes)
    lines = [f"## Placement proposal: scenario `{result.get('scenario')}`, solver `{result['solver']}`", "",
             f"- Mean latency (model): **{result['mean_latency_ms']} ms**",
             f"- Node cost: **${new_cost:.4f}/h**" + f" (was ${old_cost:.4f}/h, {new_cost - old_cost:+.4f})",
             "", "### Nodes (t3.small)", "", "| Site | Before | After | RAM used / capacity |", "|---|---|---|---|"]
    for j in REGIONS:
        m = result["memory"][j]
        lines.append(f"| {j} | {before_nodes[j]} | {new_nodes[j]} | {m['used_mi']} / {m['capacity_mi']} Mi |")
    lines += ["", "### Pods", "", "| Service | Site | Before | After |", "|---|---|---|---|"]
    after = {(s, j): n for s, p in result["placement"].items() for j, n in p["pods"].items()}
    for key in sorted(set(before_pods) | set(after)):
        b, a = before_pods.get(key, 0), after.get(key, 0)
        if a != b:
            lines.append(f"| {key[0]} | {key[1]} | {b} | {a} |")
    if all(before_pods.get(k, 0) == after.get(k, 0) for k in set(before_pods) | set(after)):
        lines.append("| (no pod changes) | | | |")
    added = {j: new_nodes[j] - before_nodes[j] for j in REGIONS}
    lines += ["", "### After merging"]
    if any(v > 0 for v in added.values()):
        lines.append("1. Terraform workflow creates the new EC2 nodes (check its plan comment).")
        lines.append("2. On your machine run `infra/ansible/join-new-nodes.sh` so k3s is installed and nodes get `region` labels.")
        lines.append("3. ArgoCD deploys the pods; they stay `Pending` until the new nodes have joined.")
    if any(v < 0 for v in added.values()):
        lines.append("**Nodes are being REMOVED**: run `kubectl drain <node> --ignore-daemonsets --delete-emptydir-data` first, "
                     "then run the Terraform workflow manually with `allow_destroy`.")
    if not any(v != 0 for v in added.values()):
        lines.append("Only pods change: ArgoCD applies them after the merge.")
    lines += ["", "_Routing shares are part of the model only; they are not deployed._"]
    return "\n".join(lines) + "\n"


def default_run(args, cwd=None):
    return subprocess.run(args, capture_output=True, text=True, check=True, cwd=cwd)


def git_commit(config_repo, message, run=default_run):
    """Stage envs/ and infra/terraform/nodes.auto.tfvars.json; commit if something changed."""
    git = lambda *a: run(["git", "-C", str(config_repo), *a])
    git("add", "-A", "envs")
    if (Path(config_repo) / NODES_FILE).exists():
        git("add", str(NODES_FILE))
    if not git("status", "--porcelain").stdout.strip():
        return False
    git("commit", "-m", message)
    return True


def propose(result, config_repo, base=None, run=default_run):
    """Branch -> write files -> commit -> push -> open a pull request. Returns (branch, pr_url)."""
    repo = str(config_repo)
    git = lambda *a: run(["git", "-C", repo, *a])
    if git("status", "--porcelain").stdout.strip():
        raise ExportError("config-repo has uncommitted changes; commit or stash them first")
    base = base or git("rev-parse", "--abbrev-ref", "HEAD").stdout.strip()
    plan_envs(result), plan_nodes(result)                                  # fail before creating a branch
    before_pods, before_nodes = read_current(config_repo)
    branch = f"placement/{result.get('scenario', 'plan')}-{time.strftime('%Y%m%d-%H%M%S')}"
    git("checkout", "-b", branch)
    try:
        write_all(result, config_repo)
        title = (f"placement({result.get('scenario')}): nodes {list(result['nodes'].values())}, "
                 f"${result['cost']}/h, {result['mean_latency_ms']} ms")
        if not git_commit(config_repo, title, run):
            git("checkout", base)
            git("branch", "-D", branch)
            return None, None
        git("push", "-u", "origin", branch)
        body = summary_markdown(result, before_pods, before_nodes)
        pr = run(["gh", "pr", "create", "--base", base, "--head", branch, "--title", title, "--body", body],
                 cwd=repo)          # gh finds the GitHub repo from the checkout in cwd
        return branch, pr.stdout.strip().splitlines()[-1] if pr.stdout.strip() else ""
    finally:
        git("checkout", base)
